def main():
    if not os.path.exists(DOCX):
        raise SystemExit("找不到买家详细故事文档")
    backup = os.path.join(os.environ.get("TEMP", "."), "买家详细故事文档.bak.docx")
    if not os.path.exists(backup):
        shutil.copy2(DOCX, backup)

    document = docx.Document(DOCX)

    for mode, anchor, new_text in PARAGRAPH_EDITS:
        paragraphs = document.paragraphs
        hits = []
        for index, paragraph in enumerate(paragraphs):
            text = paragraph.text.strip()
            if mode == "contains" and anchor in text:
                hits.append(index)
                break
            if mode == "exact" and text == anchor:
                hits.append(index)
                break
            if mode == "exact_all" and text == anchor:
                hits.append(index)
        if not hits:
            raise SystemExit("找不到段落：%s" % anchor)
        for index in hits:
            set_text(paragraphs[index], new_text)

    for table_index, row_index, col_index, new_text in CELL_EDITS:
        table = document.tables[table_index]
        set_cell(table.rows[row_index].cells[col_index], new_text)

    document.save(DOCX)
    print("updated: 买家详细故事文档（5 位买家故事线）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
